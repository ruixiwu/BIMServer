package com.yunfan.tmcc.ivr.model;

public class TexturesParaModel
{
    private String sName;
    private int sFormat;
    private int sMagfilter;
    private int sMinfilter;
    private int sWraps;
    private int sWrapt;
    private String sImagename;
    private String sImageKeyId;
    
    public TexturesParaModel() {
        super();
    }
    
    public String getsName() {
        return this.sName;
    }
    
    public void setsName(final String sName) {
        this.sName = sName;
    }
    
    public int getsFormat() {
        return this.sFormat;
    }
    
    public void setsFormat(final int sFormat) {
        this.sFormat = sFormat;
    }
    
    public int getsMagfilter() {
        return this.sMagfilter;
    }
    
    public void setsMagfilter(final int sMagfilter) {
        this.sMagfilter = sMagfilter;
    }
    
    public int getsMinfilter() {
        return this.sMinfilter;
    }
    
    public void setsMinfilter(final int sMinfilter) {
        this.sMinfilter = sMinfilter;
    }
    
    public int getsWraps() {
        return this.sWraps;
    }
    
    public void setsWraps(final int sWraps) {
        this.sWraps = sWraps;
    }
    
    public int getsWrapt() {
        return this.sWrapt;
    }
    
    public void setsWrapt(final int sWrapt) {
        this.sWrapt = sWrapt;
    }
    
    public String getsImagename() {
        return this.sImagename;
    }
    
    public void setsImagename(final String sImagename) {
        this.sImagename = sImagename;
    }
    
    public String getsImageKeyId() {
        return this.sImageKeyId;
    }
    
    public void setsImageKeyId(final String sImageKeyId) {
        this.sImageKeyId = sImageKeyId;
    }
}
